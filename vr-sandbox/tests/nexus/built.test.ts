// When each node was built or last rebuilt (src/nexus/built.ts): read from git, the time of the commit that last changed
// the line that defines it (its `id:`), so a node rebuilt after the update counts from then. UPDATE_BUILT=1 writes it
// (on a full clone: a shallow one has no history to read); without it, every node in the library must have a date.

import { describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import '../../src/nexus/seeds';
import { LIBRARY } from '../../src/nexus/blocks';
import { BUILT, UPDATE } from '../../src/nexus/built';

const files = (d: string): string[] => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? files(p) : p.endsWith('.ts') ? [p] : []; });

describe('when each node was built', () => {
  it('every node in the library has the date its definition was last changed', () => {
    if (process.env.UPDATE_BUILT) {
      // each line of every source file with the time of the commit that last changed it (now, for what is not committed)
      const lines: { file: string; text: string; t: string }[] = [];
      for (const f of files('src/nexus')) {
        let out: string; try { out = execFileSync('git', ['blame', '--line-porcelain', f], { encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] }); } catch { continue; } // (a file git does not know yet: nothing in it is a node)
        let t = '';
        for (const l of out.split('\n')) { if (l.startsWith('committer-time ')) t = new Date(Number(l.slice(15)) * 1000).toISOString(); else if (l.startsWith('\t')) lines.push({ file: f, text: l.slice(1), t }); }
      }
      const now = new Date().toISOString(), built: Record<string, string> = {}, unfound: string[] = [];
      for (const id of [...LIBRARY.keys()].sort()) {
        const key = id.startsWith('law.') ? id.slice(4) : id, inBook = id.startsWith('law.');
        const written = (k: string, book: boolean) => lines.find((l) => (!book || l.file.includes('/book/')) && (l.text.includes(`id: '${k}'`) || l.text.includes(`id: "${k}"`) || l.text.includes(`save('${k}'`)));
        // (made in a loop: the line that makes it, its id a template on its prefix)
        const prefix = id.slice(0, id.lastIndexOf('.') + 1), looped = () => lines.find((l) => l.text.includes(`id: \`${prefix}\${`) || l.text.includes(`save(\`${prefix}\${`));
        const hit = (inBook ? written(key, true) : undefined) ?? written(id, false) ?? (prefix ? looped() : undefined);
        if (hit) built[id] = hit.t || now; else unfound.push(id);
      }
      writeFileSync('src/nexus/built.ts', `// Generated by tests/nexus/built.test.ts (UPDATE_BUILT=1): when each node's definition was last changed, from git.\n// A node built before the update is said to be on the node: its tests may be flawed, and it is not yet re-checked\n// against what the update brought (laws with units, evidence, ±, materials down to their elements).\n\n/** The update: Reality step 0 (docs/REALITY.md), commit 269af04. */\nexport const UPDATE = '2026-10-28T06:21:22.000Z';\n/** Each node's id, and when it was built or last rebuilt. */\nexport const BUILT: Record<string, string> = ${JSON.stringify(built, null, 0).replace(/","/g, '",\n  "').replace('{"', '{\n  "').replace('"}', '"\n}')};\n/** Nodes whose definition could not be found written out (made in a loop): dated by nothing, so said as before the update. */\nexport const UNDATED: string[] = ${JSON.stringify(unfound)};\n`);
      return;
    }
    const missing = [...LIBRARY.keys()].filter((id) => !BUILT[id] && !id.startsWith('group.'));
    expect(missing.length, `not dated (run UPDATE_BUILT=1 on a full clone): ${missing.slice(0, 20).join(', ')}`).toBeLessThanOrEqual(0);
    expect(UPDATE).toMatch(/^2026-10-28/);
  });
});
