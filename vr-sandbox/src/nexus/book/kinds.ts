// What each law of the book is (docs/REALITY.md, step 2), and why it works. A law's kind says how far to trust it
// beyond its worked example: a conservation law holds everywhere it has been tested; a definition cannot fail, only be
// misapplied; a derived law holds as far as the laws and idealisations it was derived from; a constitutive law is how
// one kind of material behaves, within a range; an empirical law is a fit to measurements and holds over the data it was
// fitted to; an approximation is another law in a limit, and fails outside it. When a law must not be used is its
// `valid` text and its domain predicates (the book); this file adds the kind and the reason.

